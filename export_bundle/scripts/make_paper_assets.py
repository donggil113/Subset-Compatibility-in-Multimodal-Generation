    n += macro("numGapEulerSixtyFour", f"{g['euler_64_seq']['pop_D_compared_vs_reference']:.5f}")
    n += macro("numGapEulerFour", f"{g['euler_4_seq']['pop_D_compared_vs_reference']:.5f}")
