"""Generate LaTeX tables, pgfplots data and numeric macros for paper/main.tex
from committed raw results. No sampling is performed; closed-form curves are
computed with p5compat.analytic on the regenerated (digest-checked) v1 rows.

Usage: python3 scripts/make_paper_assets.py
Outputs: paper/generated/*.tex, paper/generated/*.dat
"""

