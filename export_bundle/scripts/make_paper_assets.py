    t += ("Sampler (both branches) & $D_{\\mathrm{pop}}\\times10^3$ & $\\mathbb{E}[d]\\times10^3$ & "
          "$\\bar d\\times10^3$ [95\\% CI] & $p_T$ \\\\\n\\midrule\n")
    for eid, cid, label in nrows:
        s = c(eid, cid)
        r = pred[(eid, cid)]
        t += (f"{label} & {k3(r['pop_D_target'], 3)} & {k3(r['pred_E_d'], 3)} & {ci3(s['target']['d'])} & "
              f"{pv(s['target']['p_sign_flip'])} \\\\\n")
