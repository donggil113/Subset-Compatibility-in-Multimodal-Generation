    t += ("Exp. & Condition & $M$ & $D_{\\mathrm{pop}}$ & $\\mathbb{E}[d]$ & $\\bar d$ [95\\% CI] & $z$ & "
          "$\\mathbb{E}[d_J]$ & $\\bar d_J$ \\\\\n & & & \\multicolumn{6}{c}{(all $\\times10^3$)} \\\\\n\\midrule\n")
