HEADER = "% AUTO-GENERATED by scripts/make_paper_assets.py from committed raw results. Do not edit by hand.\n"


def load(p):
    with open(p) as f:
        return json.load(f)


def k3(v, nd=2):
    """value x 1e3 formatted."""
    return "--" if v is None else f"{1e3 * v:.{nd}f}"


def ci3(b, nd=2):
    if b is None or b.get("mean") is None:
        return "--"
    return f"{k3(b['mean'], nd)} [{k3(b['lo'], nd)}, {k3(b['hi'], nd)}]"


def pv(p):
    return "--" if p is None else f"{p:.3f}"


def tt(name):
    return "\\texttt{" + name.replace("_", "\\_") + "}"


def macro(name, value):
    return f"\\newcommand{{\\{name}}}{{{value}}}\n"


