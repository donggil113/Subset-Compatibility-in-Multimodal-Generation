        ("P5-E2-CHECKER", "var_ratio_0.8", "Variance ratio 0.8"),
        ("P5-E2-CHECKER", "var_ratio_1.1", "Variance ratio 1.1"),
        ("P5-E2-CHECKER", "var_ratio_1.5", "Variance ratio 1.5"),
        ("P5-E2-CHECKER", "corr_scale_-1", "Corr.\\ scale $-1$ (target exact)"),
